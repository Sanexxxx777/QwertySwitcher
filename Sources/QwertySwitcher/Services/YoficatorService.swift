import Foundation

final class YoficatorService {
    private var yoWords: [String: String] = [:] // "еж" -> "ёж"

    init() {
        loadYoWords()
    }

    func yoficate(_ word: String) -> String? {
        guard !word.isEmpty else { return nil }
        let lowered = word.lowercased()

        if let yoVersion = yoWords[lowered] {
            // Preserve original capitalization
            if word.first?.isUppercase == true {
                return yoVersion.prefix(1).uppercased() + yoVersion.dropFirst()
            }
            return yoVersion
        }
        return nil
    }

    private func loadYoWords() {
        // Common Russian words where "е" should be "ё"
        // This is a curated list of the most frequent cases
        let pairs: [(String, String)] = [
            // Pronouns & common words
            ("ее", "её"), ("еще", "ещё"),
            ("мое", "моё"), ("свое", "своё"), ("твое", "твоё"),

            // Verbs
            ("идет", "идёт"), ("найдет", "найдёт"), ("придет", "придёт"),
            ("пойдет", "пойдёт"), ("берет", "берёт"), ("дает", "даёт"),
            ("ведет", "ведёт"), ("несет", "несёт"), ("везет", "везёт"),
            ("живет", "живёт"), ("зовет", "зовёт"), ("жмет", "жмёт"),
            ("ждет", "ждёт"), ("начнет", "начнёт"), ("поймет", "поймёт"),
            ("умрет", "умрёт"), ("пришел", "пришёл"), ("ушел", "ушёл"),
            ("нашел", "нашёл"), ("пошел", "пошёл"), ("зашел", "зашёл"),
            ("дошел", "дошёл"), ("подошел", "подошёл"),
            ("перешел", "перешёл"), ("прошел", "прошёл"), ("обошел", "обошёл"),

            // Nouns
            ("еж", "ёж"), ("елка", "ёлка"), ("елку", "ёлку"),
            ("мед", "мёд"), ("лед", "лёд"),
            ("клен", "клён"), ("озер", "озёр"),
            ("самолет", "самолёт"),
            ("счет", "счёт"), ("расчет", "расчёт"), ("учет", "учёт"),
            ("отчет", "отчёт"),
            ("черт", "чёрт"),

            // Adjectives
            ("черный", "чёрный"), ("черная", "чёрная"), ("черное", "чёрное"),
            ("черного", "чёрного"), ("черной", "чёрной"), ("черных", "чёрных"),
            ("желтый", "жёлтый"), ("желтая", "жёлтая"), ("желтое", "жёлтое"),
            ("зеленый", "зелёный"), ("зеленая", "зелёная"), ("зеленое", "зелёное"),
            ("теплый", "тёплый"), ("теплая", "тёплая"), ("теплое", "тёплое"),
            ("тяжелый", "тяжёлый"), ("тяжелая", "тяжёлая"),
            ("далекий", "далёкий"), ("далекая", "далёкая"),

            // Adverbs
            ("далеко", "далёко"),

            // Misc
            ("трех", "трёх"), ("четырех", "четырёх"),
            ("причем", "причём"),
            ("серьезный", "серьёзный"), ("серьезная", "серьёзная"),
            ("серьезно", "серьёзно"),
            ("приобрел", "приобрёл"), ("обрел", "обрёл"),
        ]

        for (from, to) in pairs {
            if from != to { // only add where there's an actual change
                yoWords[from] = to
            }
        }
        NSLog("[Yoficator] Loaded \(yoWords.count) ё-replacements")
    }
}
